class I18nManager {
  constructor() {
    this.storageKey = 'incontech_lang';
    this.defaultLang = 'es';
    this.translations = translations;
    this.currentLang = localStorage.getItem(this.storageKey) || this.defaultLang;

    if (!this.translations[this.currentLang]) {
      this.currentLang = this.defaultLang;
    }
  }

  /**
   * Register a new language dynamically.
   * @param {string} code - e.g. 'fr', 'pt'
   * @param {Object} dict - Key-value translation dictionary
   */
  registerLanguage(code, dict) {
    if (code && typeof dict === 'object') {
      this.translations[code] = Object.assign({}, this.translations[code] || {}, dict);
    }
  }

  /**
   * Get translation by key
   */
  t(key, fallback = '') {
    const dict = this.translations[this.currentLang] || this.translations[this.defaultLang];
    return dict[key] !== undefined ? dict[key] : (fallback || key);
  }

  /**
   * Set active language and trigger DOM translation update
   */
  setLanguage(langCode) {
    if (!this.translations[langCode]) {
      console.warn(`Language '${langCode}' not registered.`);
      return;
    }

    this.currentLang = langCode;
    localStorage.setItem(this.storageKey, langCode);
    document.documentElement.setAttribute('lang', langCode);

    this.updateDOM();

    // Dispatch custom event for dynamic components (tabs, projects, modals)
    window.dispatchEvent(new CustomEvent('languageChanged', {
      detail: { lang: langCode, manager: this }
    }));
  }

  /**
   * Translate all DOM elements with data-i18n attributes
   */
  updateDOM() {
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach(el => {
      const key = el.getAttribute('data-i18n');
      const translation = this.t(key);
      if (translation) {
        if (el.hasAttribute('data-i18n-html')) {
          el.innerHTML = translation;
        } else {
          el.textContent = translation;
        }
      }
    });

    // Translate attributes like placeholder, title, aria-label
    const placeholders = document.querySelectorAll('[data-i18n-placeholder]');
    placeholders.forEach(el => {
      const key = el.getAttribute('data-i18n-placeholder');
      const translation = this.t(key);
      if (translation) {
        el.setAttribute('placeholder', translation);
      }
    });

    const titles = document.querySelectorAll('[data-i18n-title]');
    titles.forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      const translation = this.t(key);
      if (translation) {
        el.setAttribute('title', translation);
      }
    });

    const arias = document.querySelectorAll('[data-i18n-aria]');
    arias.forEach(el => {
      const key = el.getAttribute('data-i18n-aria');
      const translation = this.t(key);
      if (translation) {
        el.setAttribute('aria-label', translation);
      }
    });

    // Update language dropdown options UI state & active trigger display
    const langOpts = document.querySelectorAll('.lang-dropdown__opt');
    langOpts.forEach(btn => {
      const code = btn.getAttribute('data-lang');
      if (code === this.currentLang) {
        btn.classList.add('active');
        btn.setAttribute('aria-current', 'true');

        const optFlag = btn.querySelector('.lang-dropdown__flag');
        document.querySelectorAll('.lang-dropdown').forEach(dd => {
          const triggerFlag = dd.querySelector('.lang-dropdown__trigger .lang-dropdown__flag');
          const triggerCode = dd.querySelector('.lang-dropdown__trigger span:not(.lang-dropdown__code)');
          if (triggerFlag && optFlag) {
            triggerFlag.innerHTML = optFlag.innerHTML;
          }
          if (triggerCode) {
            triggerCode.textContent = code.toUpperCase();
          }
        });
      } else {
        btn.classList.remove('active');
        btn.removeAttribute('aria-current');
      }
    });
  }

  init() {
    document.documentElement.setAttribute('lang', this.currentLang);
    this.updateDOM();
  }
}

// Global instance exported to window
window.i18n = new I18nManager();
